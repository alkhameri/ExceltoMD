import {readFile, readdir, writeFile} from 'node:fs/promises';
import path from 'node:path';

// Include licenses for the runtime modules actually present in the bundles.
export async function writeNotices(metafile) {
  const roots = new Set();
  for (const input of Object.keys(metafile.inputs)) {
    const match = input.replaceAll('\\', '/').match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//);
    if (match) roots.add(match[1]);
  }
  const notices = ['Third-party software bundled with Excel to Markdown Live\nGenerated by npm run build.'];
  for (const root of [...roots].sort()) {
    const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
    const files = (await readdir(root)).filter(name => /^(licen[sc]e|copying|notice)([._-].*)?$/i.test(name)).sort();
    const source = pkg.name === 'xlsx' ? 'https://cdn.sheetjs.com/xlsx-0.20.3/xlsx-0.20.3.tgz' : pkg.repository?.url ?? pkg.repository ?? pkg.homepage ?? '';
    const contents = await Promise.all(files.map(async name => `${name}\n${await readFile(path.join(root, name), 'utf8')}`));
    if (!files.length && pkg.name === 'isarray') {
      const readme = await readFile(path.join(root, 'README.md'), 'utf8');
      const license = readme.match(/^## License\s+([\s\S]+)/m)?.[1];
      if (license) contents.push(license.replaceAll('&lt;', '<').replaceAll('&gt;', '>'));
    }
    if (!contents.length) throw new Error(`Missing bundled license for ${pkg.name}`);
    notices.push(`${pkg.name} ${pkg.version}\nLicense: ${pkg.license}\nSource: ${source}\n\n${contents.join('\n\n')}`);
  }
  notices.push(`Visio SVG renderer (libvisio.js)\n${await readFile('vendor/visio/ORIGIN.md', 'utf8')}\n${await readFile('vendor/visio/LICENSE', 'utf8')}`);
  await writeFile('THIRD_PARTY_NOTICES.txt', notices.map(notice => notice.trimEnd()).join('\n\n' + '='.repeat(72) + '\n\n') + '\n');
}
